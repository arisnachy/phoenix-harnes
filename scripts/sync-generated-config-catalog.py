#!/usr/bin/env python3
"""Reconcile generated config declarations with the curated Chinese catalog.

Only the generated technical region is updated. Preserved translations are
never silently overwritten; unrecognized edits require manual review.
"""
from __future__ import annotations

from difflib import SequenceMatcher
from pathlib import Path
import re
import subprocess

SOURCE = Path('docs/config-catalog.md')
COUNTERPART = Path('docs/config-catalog.zh.md')
FIRST_ENTRY = '<a id="phoenix-aidsh-acp"></a>\n'


def git_head_text(path: Path) -> str:
    return subprocess.check_output(['git', 'show', f'HEAD:{path.as_posix()}'], text=True)


def partition(text: str) -> tuple[str, list[str]]:
    if text.count(FIRST_ENTRY) != 1:
        raise ValueError('Catalog entry anchor missing or ambiguous')
    head, body = text.split(FIRST_ENTRY, 1)
    return head + FIRST_ENTRY, body.splitlines(keepends=True)


def supported_localization(english: str, chinese: str) -> bool:
    if english == chinese:
        return True
    if english.startswith('Source: ') and chinese.startswith('Source: '):
        # The existing counterpart may have older source line numbers.
        normalize = lambda s: re.sub(r'(:\d+)(?=`\])', ':LINE', s)
        return normalize(english) == normalize(chinese)
    if english.startswith('Depends on: ') and chinese.startswith('Depends on: '):
        return re.sub(r'(subsystems/[^\s)]+)\.zh\.md', r'\1.md', chinese) == english
    if ' — requires ' in english and ' — 需要 ' in chinese:
        return english.replace(' — requires ', ' — 需要 ') == chinese
    return False


def localized_line(new_english: str, old_english: str = '', old_chinese: str = '') -> str:
    new_english = re.sub(r'(subsystems/[a-z-]+)\.md(?=\))', r'\1.zh.md', new_english)
    if ' — requires ' in old_english and ' — 需要 ' in old_chinese:
        new_english = new_english.replace(' — requires ', ' — 需要 ')
    return new_english


def reconcile(old_source: str, old_zh: str, new_source: str) -> str:
    old_head, old_lines = partition(old_source)
    zh_head, zh_lines = partition(old_zh)
    _, new_lines = partition(new_source)
    if len(old_lines) != len(zh_lines):
        raise ValueError('Existing translated technical lines are not positionally aligned')
    if not zh_head.startswith('<!-- Generated by') or '[English](config-catalog.md) | 中文' not in zh_head:
        raise ValueError('Unexpected localized catalog preface')
    result: list[str] = []
    for op, a, b, c, d in SequenceMatcher(None, old_lines, new_lines, autojunk=False).get_opcodes():
        if op == 'equal':
            result.extend(zh_lines[a:b])
            continue
        for index in range(a, b):
            if not supported_localization(old_lines[index], zh_lines[index]):
                raise ValueError(f'Changed region intersects translation at line {index + 1}')
        for offset, line in enumerate(new_lines[c:d]):
            previous_en = old_lines[a + offset] if a + offset < b else ''
            previous_zh = zh_lines[a + offset] if a + offset < b else ''
            result.append(localized_line(line, previous_en, previous_zh))
    final = zh_head + ''.join(result)
    fenced = re.compile(r'```ts config-catalog\n(.*?)\n```', re.DOTALL)
    if fenced.findall(new_source) != fenced.findall(final):
        raise ValueError('Verbatim generated configuration declarations diverged')
    heading = re.compile(r'^## `@phoenix-ai/[^`]+`$', re.MULTILINE)
    if heading.findall(new_source) != heading.findall(final):
        raise ValueError('Catalog package coverage diverged')
    if old_head == zh_head:
        raise ValueError('English and Chinese catalog headers unexpectedly identical')
    return final


def main() -> None:
    old_source = git_head_text(SOURCE)
    old_zh = git_head_text(COUNTERPART)
    if COUNTERPART.read_text() != old_zh:
        raise ValueError('Merged Chinese catalog was changed; refusing overwrite')
    updated = reconcile(old_source, old_zh, SOURCE.read_text())
    if updated != old_zh:
        COUNTERPART.write_text(updated)
        print('Synchronized the Chinese catalog technical declarations')
    else:
        print('Chinese catalog technical declarations are already consistent')


if __name__ == '__main__':
    main()
